"""
Prompt Generation Tool.

Responsible for extracting the final
image generation prompt from the
story analysis result.

Future Improvements:
- Prompt Enhancement
- Style Selection
- Prompt Compression
- Negative Prompt Generation
"""

from langchain_core.tools import tool

from utils.logging import get_logger

logger = get_logger(__name__)


@tool
def generate_image_prompt(
    llm_output: dict
) -> str:
    """
    Extract the generated image prompt.

    Args:
        llm_output:
            JSON response generated by agent.

    Returns:
        Image generation prompt.
    """

    logger.info(
        "Generating image prompt."
    )

    prompt = llm_output.get(
        "image_prompt",
        ""
    )

    logger.info(
        "Prompt generated successfully."
    )

    return prompt